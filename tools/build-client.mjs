// 把 src/client/*.js 拼成一个能提交的 lib/client.js。
//
// 宿主的客户端插件必须是一个自注册文件（window.__ModuleLoader__.load），
// 安装时不跑构建，所以产物要进仓库；CI 用 --check 保证产物是最新的。
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const ROOT = path.resolve(new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/u, '$1'))
const SRC = path.join(ROOT, 'src', 'client')
const OUT = path.join(ROOT, 'lib', 'client.js')
const PKG = JSON.parse(readFileSync(path.join(ROOT, 'package.json'), 'utf8'))

const HEADER = `// @generated by tools/build-client.mjs — 手工改动会在 CI 的 --check 里失败。
// ${PKG.name} — 浏览器半边：设置页、输入框开关、每条回复的朗读键。
window.__ModuleLoader__.load({
  id: ${JSON.stringify(PKG.name)},
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
    Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });
    let react = require("react");
`

const FOOTER = `
    exports.apply = apply;
    exports.inject = inject;
    return module.exports;
  },
});
`

function build() {
  const files = readdirSync(SRC)
    .filter((name) => name.endsWith('.js'))
    .sort()
  const parts = files.map((name) => {
    const body = readFileSync(path.join(SRC, name), 'utf8').replace(/\r\n/gu, '\n')
    return `\n    // ---- ${name} ----\n${body.trimEnd()}\n`
  })
  return `${HEADER}${parts.join('')}${FOOTER}`
}

const output = build()
if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(OUT, 'utf8')
  } catch {
    current = ''
  }
  if (current !== output) {
    console.error('lib/client.js 不是最新的，运行：node tools/build-client.mjs')
    process.exit(1)
  }
  console.log(`[ok] lib/client.js 最新（${output.length} 字节）`)
} else {
  writeFileSync(OUT, output, 'utf8')
  console.log(`[ok] 写入 lib/client.js（${output.length} 字节）`)
}
